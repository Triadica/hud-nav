import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {writeFileSync} from 'node:fs';
const run=(...args)=>execFileSync('calcit',args,{encoding:'utf8',stdio:['ignore','pipe','pipe'],maxBuffer:8*1024*1024});
const q=()=>JSON.parse(run('query','def','hud-nav.updater/updater','--format','json')).data;
assert.equal(run('-v').trim(),'0.30.1');
writeFileSync('acceptance/config.txt',run('query','config'));
const before=q();
assert.equal(before.tests.length,1);
assert.equal(before.tests[0].name,'operation-boundary');
const code=structuredClone(before.tests[0].code);
assert.equal(code[0],'let');
assert.equal(code.length,5);
const parse=code[4][2][1][1];
assert.equal(parse[0],'parse-cirru-edn-as');
assert.deepEqual(parse[1],['format-cirru-edn',['::',':tab','|wrong']]);
assert.deepEqual(code[4][2][2],['fn',['message'],':rejected']);
code[1].push(['invalid-op',parse[1]]);
parse[1]='invalid-op';
const operations=[['edit','add-test','hud-nav.updater/updater','operation-boundary','--overwrite','--input-format','json-ast','--code',JSON.stringify(['quote',code])]];
writeFileSync('acceptance/before.json',JSON.stringify(before,null,2));
writeFileSync('acceptance/operations.json',JSON.stringify(operations,null,2));
const args=['edit','transaction','--file','acceptance/operations.json','--format','json'];
const preview=JSON.parse(run(...args,'--dry-run'));
assert.ok(preview.scoped_revision);
writeFileSync('acceptance/preview.json',JSON.stringify(preview,null,2));
writeFileSync('acceptance/applied.json',run(...args,'--expect-revision',preview.scoped_revision));
const after=q();
const expected=structuredClone(before);
expected.tests[0].code=code;
assert.deepEqual(after,expected,'Only existing test changes; production code/schema/doc/FFI and both positive assertions remain intact');
writeFileSync('acceptance/after.json',JSON.stringify(after,null,2));
writeFileSync('acceptance/program-diff.json',run('analyze','program-diff','HEAD','--format','json'));
